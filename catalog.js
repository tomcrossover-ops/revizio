/* Liste des chapitres d'une classe/matière (tableau vide si le catalogue n'en propose pas). */
function chaptersFor(level, subject) {
  return ((CATALOG[level] || {})[subject]) || [];
}
/* Matières disponibles au catalogue pour une classe. */
function catalogSubjects(level) {
  return Object.keys(CATALOG[level] || {}).filter(k => CATALOG[level][k].length);
}
